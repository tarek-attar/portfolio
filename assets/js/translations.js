function setLanguage(lang) {
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[lang][key];
            } else {
                element.innerHTML = translations[lang][key];
            }
        }
    });

    // The globe icon handles translation toggle now via dropdown
    // We don't need to change its innerHTML anymore
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('language') || 'en';
    setLanguage(savedLang);

    const langBtn = document.getElementById('lang-toggle');
    const langMenu = document.getElementById('lang-menu');

    if (langBtn && langMenu) {
        langBtn.addEventListener('click', (e) => {
            e.preventDefault();
            langMenu.classList.toggle('show-lang');
        });

        document.querySelectorAll('.nav__lang-link').forEach(link => {
            link.addEventListener('click', (e) => {
                e.preventDefault();
                const selectedLang = e.target.getAttribute('data-lang');
                setLanguage(selectedLang);
                langMenu.classList.remove('show-lang');
            });
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
                langMenu.classList.remove('show-lang');
            }
        });
    }
});